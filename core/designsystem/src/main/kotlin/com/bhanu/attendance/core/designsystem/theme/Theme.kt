val LocalStatusColors = staticCompositionLocalOf { LightStatusColors }

/** Accessor that reads naturally at call sites: `BhanuTheme.status.success`. */
object BhanuTheme {
    val status: StatusColors
        @Composable get() = LocalStatusColors.current
}

@Composable
fun BhanuTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    /**
     * Dynamic colour is opt-out rather than on by default.
     *
     * Android 12+ wallpaper-derived colour is lovely, but status colours here carry meaning
     * (recorded vs outside the geofence) and must stay legible. A user-chosen wallpaper that
     * recolours everything can quietly destroy the contrast the palette was checked for, so
     * dynamic colour is off unless explicitly requested.
     */
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val context = LocalContext.current
    val colorScheme: ColorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S ->
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)

        darkTheme -> DarkScheme
        else -> LightScheme
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window ?: return@SideEffect
            // Draw behind the system bars and ensure icon contrast is correct in each theme.
            // Without this, edge-to-edge content renders under a status bar with unreadable
            // icons, which is a visible defect on every launch.
            WindowCompat.setDecorFitsSystemWindows(window, false)
            WindowCompat.getInsetsController(window, view).apply {
                isAppearanceLightStatusBars = !darkTheme
                isAppearanceLightNavigationBars = !darkTheme
            }
        }
    }

    CompositionLocalProvider(
        LocalStatusColors provides if (darkTheme) DarkStatusColors else LightStatusColors,
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = BhanuTypography,
            shapes = BhanuShapes,
            content = content,
        )
    }
}
